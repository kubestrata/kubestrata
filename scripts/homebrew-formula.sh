#!/bin/sh
# Prints the Homebrew formula for a kubestrata release.
# Usage: scripts/homebrew-formula.sh <version without v> <path to checksums.txt>
# Used by .github/workflows/release.yml and for a manual tap update.
set -eu

version="${1:?version}"
checksums="${2:?checksums.txt}"

case "$version" in
  [0-9]*.[0-9]*.[0-9]*) ;;
  *) echo "invalid version: $version" >&2; exit 1 ;;
esac

sum() {
  s="$(awk -v f="kubestrata_${version}_$1.tar.gz" '$2 == f { print $1 }' "$checksums")"
  case "$s" in
    [0-9a-f]*) [ "${#s}" -eq 64 ] || { echo "bad sha256 for $1" >&2; exit 1; } ;;
    *) echo "no sha256 for $1 in $checksums" >&2; exit 1 ;;
  esac
  printf '%s' "$s"
}

# Resolve every checksum first: a failure inside $(...) in the heredoc
# would not stop the script.
darwin_arm64="$(sum darwin_arm64)"
darwin_amd64="$(sum darwin_amd64)"
linux_arm64="$(sum linux_arm64)"
linux_amd64="$(sum linux_amd64)"

base="https://github.com/kubestrata/kubestrata/releases/download/v${version}"

cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by scripts/homebrew-formula.sh in kubestrata/kubestrata. Do not edit by hand.
class Kubestrata < Formula
  desc "Read-only, time-layered inventory of Kubernetes clusters for migration planning"
  homepage "https://github.com/kubestrata/kubestrata"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/kubestrata_${version}_darwin_arm64.tar.gz"
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "${base}/kubestrata_${version}_darwin_amd64.tar.gz"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/kubestrata_${version}_linux_arm64.tar.gz"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base}/kubestrata_${version}_linux_amd64.tar.gz"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install "kubestrata"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/kubestrata --version")
    (testpath/"kubeconfig").write <<~YAML
      apiVersion: v1
      kind: Config
      clusters:
      - name: smoke
        cluster:
          server: https://127.0.0.1:1
      contexts:
      - name: smoke
        context:
          cluster: smoke
          user: smoke
      current-context: smoke
      users:
      - name: smoke
        user:
          token: not-a-real-token
    YAML
    output = shell_output("#{bin}/kubestrata --kubeconfig #{testpath}/kubeconfig contexts --format json")
    assert_match '"current": "smoke"', output
    refute_match "not-a-real-token", output
  end
end
EOF
